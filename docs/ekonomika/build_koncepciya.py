def shade(cell, fill: str) -> None:
    tc = cell._tc.get_or_add_tcPr()
    sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear")
    sh.set(qn("w:color"), "auto")
    sh.set(qn("w:fill"), fill)
    tc.append(sh)


def borders(table, color: str = "C9C2DA") -> None:
    tbl_pr = table._tbl.tblPr
    el = OxmlElement("w:tblBorders")
    for side in ("top", "left", "bottom", "right", "insideH", "insideV"):
        b = OxmlElement(f"w:{side}")
        b.set(qn("w:val"), "single")
        b.set(qn("w:sz"), "4")
        b.set(qn("w:color"), color)
        el.append(b)
    tbl_pr.append(el)


def runs(paragraph, text: str, size: float | None = None, color=None) -> None:
    """**жирный** внутри строки."""
    parts = text.split("**")
    for i, part in enumerate(parts):
        if not part:
            continue
        r = paragraph.add_run(part)
        r.bold = i % 2 == 1
        if size:
            r.font.size = Pt(size)
        if color is not None:
            r.font.color.rgb = color


def h1(text):
    doc.add_heading(text, level=1)


def h2(text):
    doc.add_heading(text, level=2)


def h3(text):
    doc.add_heading(text, level=3)


def para(text: str, size: float | None = None, color=None, italic: bool = False, align=None):
    p = doc.add_paragraph()
    runs(p, text, size, color)
    if italic:
        for r in p.runs:
            r.italic = True
    if align is not None:
        p.alignment = align
    return p


def bullets(items: list[str], style: str = "List Bullet") -> None:
    for item in items:
        runs(doc.add_paragraph(style=style), item)


def row_flags(row, header: bool = False) -> None:
    tr = row._tr.get_or_add_trPr()
    tr.append(OxmlElement("w:cantSplit"))
    if header:
        tr.append(OxmlElement("w:tblHeader"))


def table(header: list[str] | None, rows: list[list[str]], widths: list[float], size: float = 9.5,
          first_bold: bool = False) -> None:
    t = doc.add_table(rows=1 if header else 0, cols=len(widths))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    borders(t)
    if header:
        row_flags(t.rows[0], header=True)
        for cell, text, w in zip(t.rows[0].cells, header, widths):
            cell.width = Cm(w)
            shade(cell, HEAD_FILL)
            p = cell.paragraphs[0]
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.keep_with_next = True      # шапка не остаётся одна внизу страницы
            runs(p, f"**{text}**", size)
    for row in rows:
        new = t.add_row()
        row_flags(new)
        cells = new.cells
        if row[0].startswith("**") and not any(x.strip() for x in row[1:]):
            # строка-раздел («Постоянные», «Переменные»): во всю ширину, с заливкой
            merged = cells[0].merge(cells[-1])
            shade(merged, NOTE_FILL)
            q = merged.paragraphs[0]
            q.paragraph_format.space_after = Pt(0)
            q.paragraph_format.keep_with_next = True
            runs(q, row[0], size)
            continue
        for k, (cell, text, w) in enumerate(zip(cells, row, widths)):
            cell.width = Cm(w)
            lines = text.split("\n")
            p = cell.paragraphs[0]
            p.paragraph_format.space_after = Pt(0)
            runs(p, f"**{lines[0]}**" if first_bold and k == 0 and "**" not in lines[0] else lines[0], size)
            for line in lines[1:]:
                q = cell.add_paragraph()
                q.paragraph_format.space_after = Pt(0)
                runs(q, line, size)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def box(title: str, lines: list[str], fill: str = NOTE_FILL) -> None:
    """Выделенный блок: «коротко», «важно»."""
    t = doc.add_table(rows=1, cols=1)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    borders(t, "D9D2E9" if fill == NOTE_FILL else "F0C987")
    cell = t.rows[0].cells[0]
    cell.width = Cm(17.2)
    shade(cell, fill)
    p = cell.paragraphs[0]
    runs(p, f"**{title}**", 10.5, ACCENT)
    for line in lines:
        q = cell.add_paragraph(style="List Bullet")
        q.paragraph_format.space_after = Pt(2)
        runs(q, line, 10)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


