# ---------- расчёт ----------

def pert(o, m, p):
    return (o + 4 * m + p) / 6


def sigma(o, p):
    return (p - o) / 6


def stage_sum(st):
    rows = st["rows"]
    e = sum(pert(r[3], r[4], r[5]) for r in rows)
    s = sum(sigma(r[3], r[5]) for r in rows)
    return {
        "o": sum(r[3] for r in rows), "m": sum(r[4] for r in rows), "p": sum(r[5] for r in rows),
        "e": e, "s": s, "e90": e + Z90 * s,
    }


SUMS = {st["key"]: stage_sum(st) for st in STAGES}
TOTAL_KEYS = [st["key"] for st in STAGES if st["in_total"]]
TOTAL = {
    "e": sum(SUMS[k]["e"] for k in TOTAL_KEYS),
    "s": sum(SUMS[k]["s"] for k in TOTAL_KEYS),
}
TOTAL["e90"] = TOTAL["e"] + Z90 * TOTAL["s"]
AHEAD = {"e": SUMS["1"]["e"] + SUMS["2"]["e"], "s": SUMS["1"]["s"] + SUMS["2"]["s"]}
AHEAD["e90"] = AHEAD["e"] + Z90 * AHEAD["s"]


