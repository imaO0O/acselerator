HEAD = PatternFill("solid", fgColor="E9E4F3")
STAGE_FILL = PatternFill("solid", fgColor="F4F1FA")
INPUT = PatternFill("solid", fgColor="FFF4E5")
BOLD = Font(bold=True)
TITLE = Font(bold=True, size=14, color="4B3A75")
THIN = Side(style="thin", color="D0C8E0")
BOX = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
WRAP = Alignment(wrap_text=True, vertical="top")
DAYS = "0.0"
MONEY = "#,##0"


def style_row(ws, row, ncols, fill=None, bold=False):
    for c in range(1, ncols + 1):
        cell = ws.cell(row=row, column=c)
        cell.border = BOX
        cell.alignment = WRAP
        if fill:
            cell.fill = fill
        if bold:
            cell.font = BOLD


