def d(x):
    """Число человеко-дней: целое, если целое, иначе один знак, с запятой."""
    return f"{x:.0f}" if abs(x - round(x)) < 0.05 else f"{x:.1f}".replace(".", ",")


def r0(x):
    """Итог в человеко-днях — целым числом: точность до десятых у оценки ложная."""
    return f"{round(x)}"


def rub(x):
    return f"{x / 1e6:.2f}".replace(".", ",") + " млн ₽"


def num(x, step=1):
    return f"{round(x / step) * step:,}".replace(",", " ")


def md_stage(st):
    s = SUMS[st["key"]]
    out = [f"## {st['title']}", "", f"*{st['when']}.* {st['note']}", "",
           "| № | Работа | Кто | О | В | П | Ожидаемо | Основание |",
           "|---|---|---|---|---|---|---|---|"]
    for n, work, who, o, m, p, why in st["rows"]:
        out.append(f"| {n} | {work} | {who} | {o} | {m} | {p} | {d(pert(o, m, p))} | {why} |")
    out.append(f"| | **Итого по этапу** | | **{s['o']}** | **{s['m']}** | **{s['p']}** | **{r0(s['e'])}** | "
               f"с запасом — **{r0(s['e90'])}** |")
    out.append("")
    return out


