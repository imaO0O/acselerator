def build_docx(blocks: list[tuple]) -> None:
    from docx import Document
    from docx.shared import Cm, Pt, RGBColor
    doc = Document()
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Cm(21), Cm(29.7)
    sec.left_margin, sec.right_margin, sec.top_margin, sec.bottom_margin = Cm(2), Cm(1.5), Cm(1.6), Cm(1.6)
    st = doc.styles["Normal"]
    st.font.name, st.font.size = "Arial", Pt(10)
    st.paragraph_format.space_after = Pt(4)
    accent = RGBColor(0x4B, 0x3A, 0x75)
    for b in blocks:
        kind = b[0]
        if kind == "title":
            r = doc.add_paragraph().add_run(b[1])
            r.bold, r.font.size, r.font.color.rgb = True, Pt(16), accent
        elif kind == "h":
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(10)
            r = p.add_run(b[1])
            r.bold, r.font.size, r.font.color.rgb = True, Pt(12), accent
        elif kind == "p":
            doc.add_paragraph(b[1])
        elif kind == "ul":
            for item in b[1]:
                doc.add_paragraph(item, style="List Bullet")
        elif kind == "table":
            head, rows = b[1], b[2]
            t = doc.add_table(rows=1, cols=len(head))
            t.style = "Table Grid"
            for cell, h in zip(t.rows[0].cells, head):
                cell.text = h
                for run in cell.paragraphs[0].runs:
                    run.bold = True
            for row in rows:
                for cell, v in zip(t.add_row().cells, row):
                    cell.text = str(v)
            for row in t.rows:
                for cell in row.cells:
                    for par in cell.paragraphs:
                        for run in par.runs:
                            run.font.size = Pt(9)
            doc.add_paragraph()
    doc.save(OUT_DOCX)


def build_md(blocks: list[tuple]) -> None:
    out = []
    for b in blocks:
        kind = b[0]
        if kind == "title":
            out += [f"# {b[1]}", ""]
        elif kind == "h":
            out += [f"## {b[1]}", ""]
        elif kind == "p":
            out += [b[1], ""]
        elif kind == "ul":
            out += [f"- {x}" for x in b[1]] + [""]
        elif kind == "table":
            head, rows = b[1], b[2]
            out += ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
            out += ["| " + " | ".join(str(v) for v in row) + " |" for row in rows] + [""]
    OUT_MD.write_text("\n".join(out), encoding="utf-8")


def build_docs() -> None:
    blocks = content()
    build_docx(blocks)
    build_md(blocks)
    print(OUT_DOCX, OUT_MD, sep="\n")


if __name__ == "__main__":
    build_docs()
