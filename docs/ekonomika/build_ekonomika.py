def mln(x: float) -> str:
    return f"{x / 1e6:.2f}".replace(".", ",") + " млн ₽"


def tys(x: float) -> str:
    return f"{round(x / 1000):,}".replace(",", " ") + " тыс. ₽"


def rub(x: float) -> str:
    return f"{round(x):,}".replace(",", " ") + " ₽"


def pct(x: float) -> str:
    return f"{x * 100:.0f} %"


def num(x: float, d: int = 1) -> str:
    return f"{x:.{d}f}".replace(".", ",")


