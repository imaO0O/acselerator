def main(flt: str = "") -> None:
    agent = Agent()
    out = []
    for cid, role, q, expect in CASES:
        if flt and not cid.startswith(flt):
            continue
        t0 = time.time()
        try:
            r = agent.ask(q, role=role, user="tester_u2")
            cited = [s["label"] for s in r.sources if s.get("cited")]
            rec = {"id": cid, "role": role, "q": q, "expect": expect, "status": r.status, "route": r.route,
                   "asked": r.asked, "text": r.text, "sources": cited, "rows": len(r.rows), "sql": r.sql,
                   "options": r.options, "sec": round(time.time() - t0, 1)}
        except Exception as e:  # noqa: BLE001
            rec = {"id": cid, "role": role, "q": q, "expect": expect, "status": "EXCEPTION", "text": repr(e)[:300]}
        out.append(rec)
        print(f"\n### {cid} [{role}] {q}\n    ждём: {expect}\n    → {rec['status']} / {rec.get('route')} / "
              f"{rec.get('sec')} с; понял как: {rec.get('asked')}\n    {rec['text'][:900]}\n    источники: "
              f"{rec.get('sources')}; записей: {rec.get('rows')}; варианты: {rec.get('options')}")
    path = Path(__file__).with_name("agent_results.json")
    json.dump(out, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "")
