"""Пробелы в документации (kbagent/gaps.py) на подставных записях журнала."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))   # корень репозитория
from kbagent.gaps import find_gaps  # noqa: E402

ENG, MET = "Инженер производства", "Метролог"


def rec(q, status="no_data", role=ENG, user="ivanov", t="2026-10-06 10:00", **kw):
    return {"question": q, "status": status, "role": role, "user": user, "time": t, "route": "documents", **kw}


def show(title, records):
    gaps, summary = find_gaps(records)
    print(f"\n=== {title}\n    сводка: {summary}")
    for g in gaps:
        state = f"ЗАКРЫТ {g['closed']}" if g["closed"] else "открыт"
        print(f"    [{state}] «{g['question']}» ×{g['count']}; другие: {g['other']}; ответ есть для: {g['other_roles']}")


# 1. Разные пробелы с похожими словами — должны быть разными темами
show("разные вопросы с общими словами", [
    rec("Сколько стоит поверка осциллографа?", t="2026-10-06 10:00"),
    rec("Сколько стоит ремонт осциллографа?", t="2026-10-06 10:01", user="petrov"),
    rec("Сколько стоит калибровка осциллографа?", t="2026-10-06 10:02", user="sidorov"),
    rec("Где лежит флюс ФКТ?", t="2026-10-06 10:03"),
    rec("Где лежит припой ПОС-40?", t="2026-10-06 10:04"),
])

# 2. Пробел закрыт ответом из неутверждённого документа или одним ответом на общий вопрос
show("закрытие пробела", [
    rec("Какая температура пайки ПОС-61 в селективной ванне?", t="2026-10-06 10:00"),
    rec("Какая температура пайки ПОС-61 в селективной ванне?", status="answer", t="2026-10-06 11:00",
        user="admin", role=ENG, sources=[{"doc_kind": "загружен пользователем, не утверждён"}]),
])

# 3. Сотрудник спрашивает про закрытый для роли документ; администратор проверил — ответ есть
show("права доступа", [
    rec("За сколько дней метролог уведомляет о поверке?", t="2026-10-06 10:00"),
    rec("За сколько дней метролог уведомляет о поверке?", status="answer", role="Администратор", user="admin",
        t="2026-10-06 10:05"),
])

# 4. Вопрос из одних служебных слов и очень короткие вопросы
show("короткие вопросы", [
    rec("А?", t="2026-10-06 10:00"),
    rec("Что делать?", t="2026-10-06 10:01"),
    rec("Как быть?", t="2026-10-06 10:02"),
    rec("Можно?", t="2026-10-06 10:03"),
])
