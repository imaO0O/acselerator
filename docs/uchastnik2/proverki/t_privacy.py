"""Проверка маскирования персональных данных (kbagent/privacy.py) на трудных написаниях."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))   # корень репозитория
from kbagent.privacy import mask  # noqa: E402

CASES = [
    # (что проверяем, текст, что не должно остаться в журнале)
    ("ФИО, им. падеж", "Иванов Иван Иванович просит допуск", "Иван Иванович"),
    ("ФИО, род. падеж", "Где пропуск Белова Игоря Николаевича?", "Николаевича"),
    ("ФИО, дат. падеж", "Передайте Сидоровой Анне Петровне акт", "Петровне"),
    ("ФИО, порядок И О Ф", "Иван Петрович Сидоров уволен?", "Сидоров"),
    ("ФИО, отчество на -ич", "Кузьмин Фома Ильич заболел", "Ильич"),
    ("ФИО строчными", "иванов иван иванович просит допуск", "иванович"),
    ("ФИО прописными", "ИВАНОВ ИВАН ИВАНОВИЧ", "ИВАНОВИЧ"),
    ("ФИО, двойная фамилия", "Римская-Корсакова Мария Андреевна", "Римская"),
    ("телефон моб.", "мой телефон +7 (910) 123-45-67", "123-45-67"),
    ("телефон городской Рязань", "звоните 8 (4912) 12-34-56", "12-34-56"),
    ("телефон без кода", "сотовый 9101234567", "9101234567"),
    ("СНИЛС без дефисов", "СНИЛС 12345678901", "12345678901"),
    ("паспорт со словами", "паспорт серия 6123 номер 456789", "456789"),
    ("ИНН 12 цифр", "ИНН 623012345678", "623012345678"),
    ("почта", "пишите ivanov.i@npvp-ntp.ru", "ivanov"),
    ("дата рождения", "дата рождения 12.03.1990", "1990"),
    ("адрес", "живу на ул. Гагарина, д. 59, кв. 12", "кв. 12"),
    # не должно маскироваться — рабочие сведения
    ("внутр. телефон (оставить)", "телефон диспетчера 2211", None),
    ("инициалы (оставить)", "ответственный Белов И. Н.", None),
    ("номер партии (оставить)", "партия П-2609-04, 120 шт", None),
    ("дата и количество (оставить)", "поступило 02.10.2026 120 шт", None),
]

leaks, over = [], []
for what, text, secret in CASES:
    out = mask(text)
    if secret is None:
        status = "ok" if out == text else "ИСКАЖЕНО"
        if out != text:
            over.append(what)
    else:
        status = "ok" if secret not in out else "УТЕЧКА"
        if secret in out:
            leaks.append(what)
    print(f"{status:8} | {what:30} | {out}")
print(f"\nутечек: {len(leaks)} из {sum(1 for c in CASES if c[2])}; лишних масок: {len(over)}")
