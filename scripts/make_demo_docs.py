def find_font():
    """Шрифт с кириллицей: Times New Roman в Windows, DejaVu Serif в Linux."""
    candidates = [
        (Path(os.environ.get("WINDIR", "C:/Windows")) / "Fonts", "times.ttf", "timesbd.ttf"),
        (Path("/usr/share/fonts/truetype/dejavu"), "DejaVuSerif.ttf", "DejaVuSerif-Bold.ttf"),
    ]
    for folder, regular, bold in candidates:
        if (folder / regular).exists() and (folder / bold).exists():
            return folder, regular, bold
    raise RuntimeError("Не найден шрифт с кириллицей (Times New Roman или DejaVu Serif)")


def build_pdf(name: str, spec: dict) -> Path:
    folder, regular, bold = find_font()
    css = f"""
        @font-face {{ font-family: doc; src: url({regular}); }}
        @font-face {{ font-family: doc; font-weight: bold; src: url({bold}); }}
        * {{ font-family: doc; font-size: 12pt; }}
        .demo {{ font-size: 9pt; color: #C00000; }}
        .c {{ text-align: center; }}
        h2 {{ font-size: 13pt; font-weight: bold; margin: 10pt 0 4pt 0; }}
        p {{ text-align: justify; margin: 0 0 5pt 0; }}
        p.i {{ text-indent: 1cm; }}
    """
    esc = html.escape
    parts = [
        f'<p class="demo">{esc(DEMO_NOTE)}</p>',
        f'<p class="c">{esc(COMPANY)}</p>',
        f'<p class="c"><b>{esc(spec["code"])}</b></p>',
        f'<p class="c"><b>{esc(spec["title"].upper())}</b></p>',
        f"<p>Дата введения: {spec.get('date', '01.03.2026')}</p>",
    ]
    for kind, text in spec["body"]:
        parts.append(f"<h2>{esc(text)}</h2>" if kind == "h" else f'<p class="i">{esc(text)}</p>')

    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / f"{name}.pdf"
    story = pymupdf.Story("".join(parts), user_css=css, archive=pymupdf.Archive(str(folder)))
    page_rect = pymupdf.paper_rect("a4")
    writer = pymupdf.DocumentWriter(str(path))
    more = True
    while more:
        device = writer.begin_page(page_rect)
        more, _ = story.place(page_rect + (60, 56, -50, -70))
        story.draw(device)
        writer.end_page()
    writer.close()

    # номера страниц в нижнем колонтитуле
    doc = pymupdf.open(path)
    for i, page in enumerate(doc):
        page.insert_font(fontname="F0", fontfile=str(folder / regular))
        page.insert_text((page_rect.width / 2 - 40, page_rect.height - 36),
                         f"Страница {i + 1} из {len(doc)}", fontname="F0", fontsize=9)
    doc.save(path, incremental=True, encryption=pymupdf.PDF_ENCRYPT_KEEP)
    return path


def build_docx(name: str, spec: dict) -> Path:
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(12)

    banner = doc.add_paragraph()
    run = banner.add_run(DEMO_NOTE)
    run.italic = True
    run.font.size = Pt(9)
    run.font.color.rgb = RGBColor(0xC0, 0x00, 0x00)

    for text, size, bold in ((COMPANY, 11, False), (spec["code"], 12, True), (spec["title"].upper(), 14, True)):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(text)
        r.bold = bold
        r.font.size = Pt(size)
    doc.add_paragraph(f"Дата введения: {spec.get('date', '01.03.2026')}")
    if spec.get("status") == "отменён":
        doc.add_paragraph("Документ отменён. Действует новая редакция.").runs[0].bold = True

    for kind, text in spec["body"]:
        if kind == "h":
            doc.add_heading(text, level=2)
        else:
            doc.add_paragraph(text).paragraph_format.first_line_indent = Pt(28)

    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / f"{name}.docx"
    doc.save(path)
    return path


